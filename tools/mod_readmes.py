"""Write mods/NNNN-slug/README.md for every mod, from its mod.toml.

Each README is generated: edit mod.toml (or docs/MANUAL.md) and run

    python3 tools/mod_readmes.py

so a mod's folder reads on its own when browsed on GitHub. Standard library only.
"""
from __future__ import annotations

import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODS = ROOT / "mods"
MANUAL = ROOT / "docs" / "MANUAL.md"

FILES = {
    "mod.toml": "manifest: id, status, summary, build parameters",
    "stub.s": "the patch source (GNU as, ColdFire)",
    "design.md": "design rationale",
}


def anchor(heading: str) -> str:
    """GitHub's anchor for a markdown heading."""
    a = heading.strip().lower()
    a = re.sub(r"[^\w\- ]", "", a)
    return a.replace(" ", "-")


def manual_sections() -> dict[str, str]:
    """mod number -> the MANUAL.md heading that describes it."""
    out = {}
    for line in MANUAL.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^## (\d{4}) - (.+)$", line)
        if m:
            out[m.group(1)] = line[3:].strip()
    return out


def claims(mod_id: str) -> dict[str, int]:
    reg = tomllib.loads((ROOT / "registry" / "allocations.toml").read_text(encoding="utf-8"))
    n = {}
    for kind in ("cave", "patch", "detour"):
        n[kind] = sum(1 for c in reg.get(kind, []) if c.get("owner") == mod_id)
    return n


def render(d: Path, sections: dict[str, str]) -> str:
    meta = tomllib.loads((d / "mod.toml").read_text(encoding="utf-8"))
    m = meta["mod"]
    num = m["id"][:4]
    lines = [f"# {m['id']}", "", f"**{m['title']}**", ""]
    enabled = "yes" if m.get("enabled") else "no (build it with `--mods`)"
    lines += [
        "| | |",
        "|---|---|",
        f"| status | `{m.get('status', '?')}` |",
        f"| in the default build | {enabled} |",
    ]
    if m.get("excludes"):
        lines.append(f"| cannot be built with | {', '.join(m['excludes'])} |")
    c = claims(m["id"])
    lines.append(f"| registry claims | {c['cave']} cave, {c['detour']} detour, {c['patch']} patch |")
    lines.append("")
    if num in sections:
        h = sections[num]
        lines += [f"How to use it on the device: [docs/MANUAL.md, {h}]"
                  f"(../../docs/MANUAL.md#{anchor(h)}).", ""]
    lines += ["## What it does and how", "", m.get("summary", "").strip(), ""]
    params = meta.get("params")
    if params:
        lines += ["## Build parameters", "", "Set in `mod.toml` under `[params]`:", ""]
        lines += [f"- `{k}` = `{v}`" for k, v in params.items()]
        lines.append("")
    lines += ["## Files", ""]
    for f in sorted(p.name for p in d.iterdir() if p.is_file() and p.name != "README.md"):
        lines.append(f"- `{f}`" + (f": {FILES[f]}" if f in FILES else ""))
    lines += [
        "",
        "Addresses are into the MAIN OS of stock Analog Rytm MKII OS 1.73, loaded",
        "at 0x40000400. Every cave, detour and patch is claimed in",
        "`registry/allocations.toml`, with the stock bytes it expects. The stock",
        "firmware is not part of this repository; see the top-level README to build.",
        "",
        "<!-- generated by tools/mod_readmes.py from mod.toml; do not edit -->",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    sections = manual_sections()
    for d in sorted(p for p in MODS.iterdir() if (p / "mod.toml").is_file()):
        (d / "README.md").write_text(render(d, sections), encoding="utf-8", newline="\n")
        print(f"wrote {d.relative_to(ROOT)}/README.md")


if __name__ == "__main__":
    main()
